import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const RAW_DIR = path.resolve('src/assets/media/raw');
const OUT_DIR = path.resolve('public/media');
const MANIFEST_OUT = path.resolve('src/config/media.generated.ts');

const WIDTHS = [480, 960, 1600];

fs.mkdirSync(OUT_DIR, { recursive: true });

const files = fs
  .readdirSync(RAW_DIR)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort();

const entries = {};

for (const file of files) {
  const id = file.replace(/\.[^.]+$/, '');
  const inputPath = path.join(RAW_DIR, file);
  const meta = await sharp(inputPath).metadata();
  const baseWidth = meta.width ?? 1200;
  const baseHeight = meta.height ?? 900;

  const targetWidths = WIDTHS.filter((w) => w < baseWidth);
  if (!targetWidths.includes(baseWidth) && baseWidth <= 1800) {
    targetWidths.push(baseWidth);
  }
  if (targetWidths.length === 0) {
    targetWidths.push(baseWidth);
  }

  const avifSrcset = [];
  const webpSrcset = [];

  for (const w of targetWidths) {
    const avifName = `${id}-${w}.avif`;
    const webpName = `${id}-${w}.webp`;

    await sharp(inputPath)
      .resize({ width: w, withoutEnlargement: true })
      .avif({ quality: 68, effort: 4 })
      .toFile(path.join(OUT_DIR, avifName));

    await sharp(inputPath)
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: 82 })
      .toFile(path.join(OUT_DIR, webpName));

    avifSrcset.push(`/media/${avifName} ${w}w`);
    webpSrcset.push(`/media/${webpName} ${w}w`);
  }

  const lqipBuffer = await sharp(inputPath)
    .resize({ width: 24 })
    .webp({ quality: 45 })
    .toBuffer();

  const fallbackW = targetWidths[Math.min(1, targetWidths.length - 1)];

  entries[id] = {
    id,
    width: baseWidth,
    height: baseHeight,
    aspectRatio: Number((baseWidth / baseHeight).toFixed(4)),
    fallbackSrc: `/media/${id}-${fallbackW}.webp`,
    avifSrcset: avifSrcset.join(', '),
    webpSrcset: webpSrcset.join(', '),
    lqip: `data:image/webp;base64,${lqipBuffer.toString('base64')}`,
  };
}

const tsOutput = `// Auto-generated by scripts/optimize-media.mjs — do not hand-edit.
export interface MediaAssetEntry {
  id: string;
  width: number;
  height: number;
  aspectRatio: number;
  fallbackSrc: string;
  avifSrcset: string;
  webpSrcset: string;
  lqip: string;
}

export const GENERATED_MEDIA: Record<string, MediaAssetEntry> = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(MANIFEST_OUT, tsOutput, 'utf8');
console.log(`Optimized ${files.length} visual assets -> public/media & src/config/media.generated.ts`);
